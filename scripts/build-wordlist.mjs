#!/usr/bin/env node
// Generate the packed BIP-39 prefix table the ingress gate checks against.
//
//   bun run build:wordlist
//
// The wallet needs to recognise a recovery phrase in a message before that
// message can be sent anywhere. Doing that by heuristic — "twelve short
// lowercase words" — misfires on ordinary English and, worse, misses a real
// phrase that happens not to fit the shape. The list is the only exact answer.
//
// Only the first four characters of each word are kept. BIP-39 guarantees those
// four are unique across the 2048 words, so the table is a quarter of the size
// and loses nothing: position in the table is still the word's index, which is
// all the standard uses it for.
//
// The English list is frozen by BIP-39 and cannot change, so the generated file
// is committed rather than built on every install. This script exists so anyone
// can regenerate it and diff the result.

import { writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { wordlist } from "@scure/bip39/wordlists/english";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = join(root, "public", "tera", "core", "wordlist.js");

const WIDTH = 4;

if (wordlist.length !== 2048) throw new Error(`Expected 2048 words, got ${wordlist.length}.`);
const prefixes = wordlist.map((word) => word.slice(0, WIDTH).padEnd(WIDTH, " "));
if (new Set(prefixes).size !== prefixes.length)
  throw new Error(`The first ${WIDTH} characters are not unique across the list.`);

const packed = prefixes.join("");
const lines = [];
for (let index = 0; index < packed.length; index += 80) lines.push(packed.slice(index, index + 80));

const file = `// The BIP-39 English wordlist, packed.
//
// Generated by scripts/build-wordlist.mjs — do not edit by hand.
//
// Each word is stored as its first ${WIDTH} characters, which BIP-39 guarantees are
// unique across all 2048. A word's position here is its index in the standard,
// so nothing is lost by dropping the tails.
//
// This exists so that ${"`"}ingress.js${"`"} can tell a recovery phrase from a sentence
// exactly, rather than guessing from word shapes. It is a fixed standard: the
// English list is frozen and this file should never need to change.

export const PREFIX_WIDTH = ${WIDTH};
export const COUNT = ${wordlist.length};

const PACKED =
${lines.map((line) => `  "${line}"`).join(" +\n")};

// Built once, on first use. Scanning the packed string with indexOf looks
// cheaper and is wrong: "bana" first appears at offset 1, inside
// "abandon"+"ability", so a straight search finds a fragment spanning two
// neighbouring words and never reaches the real entry. Only boundaries count,
// and a map is the honest way to say that.
let INDEX = null;

function table() {
  if (INDEX) return INDEX;
  INDEX = new Map();
  for (let at = 0; at < PACKED.length; at += PREFIX_WIDTH)
    INDEX.set(PACKED.slice(at, at + PREFIX_WIDTH), at / PREFIX_WIDTH);
  return INDEX;
}

/** The word's index in the standard list, or -1. Case and spacing are the caller's problem. */
export function indexOf(word) {
  if (typeof word !== "string" || word.length < 1) return -1;
  const found = table().get(word.slice(0, PREFIX_WIDTH).padEnd(PREFIX_WIDTH, " "));
  return found === undefined ? -1 : found;
}

/** Whether a word is in the list. */
export function isWord(word) {
  return indexOf(word) >= 0;
}
`;

await writeFile(output, file, "utf8");
console.log(`${wordlist.length} words · ${packed.length} chars → ${relative(root, output)}`);
