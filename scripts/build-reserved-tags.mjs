#!/usr/bin/env node
// Publish the reserved tag list for the deploy script to seed on-chain.
//
//   bun run build:reserved-tags
//
// `RESERVED` in public/tera/core/tags.js is what the wallet refuses to let an
// owner claim. That refusal is worth nothing on its own — anyone can call
// TagRegistry.claim directly and take `@support` without going near the app —
// so the same list has to exist on-chain, and the two have to agree.
//
// Rather than maintaining a Solidity copy that drifts, the list is written here
// as JSON, read by Deploy.s.sol, and checked against tags.js by
// tests/frontend/tags-reserved.test.js. A name added to the module and not
// re-published fails that test rather than quietly being claimable.

import { readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { RESERVED } from "../public/tera/core/tags.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = join(root, "contracts", "reserved-tags.json");

// Sorted so the file is stable across runs and a diff shows only real changes.
const tags = [...RESERVED].sort();

const document = {
  note: "Generated by scripts/build-reserved-tags.mjs from public/tera/core/tags.js. Seeded on-chain by contracts/script/Deploy.s.sol; do not edit by hand.",
  tags,
};

const next = `${JSON.stringify(document, null, 2)}\n`;
const current = await readFile(output, "utf8").catch(() => "");

if (current === next) {
  console.log(`${relative(root, output)} is already current (${tags.length} names).`);
} else {
  await writeFile(output, next);
  console.log(`Wrote ${relative(root, output)} — ${tags.length} reserved names.`);
}
